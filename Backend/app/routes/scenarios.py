@scenarios_bp.get("/scenarios")
def get_scenarios():
    """List available earthquake scenarios for demonstration and testing."""
    return jsonify({
        "count": len(SCENARIOS),
        "scenarios": [
            {
                "id": s["id"],
                "name": s["name"],
                "short_name": s["short_name"],
                "tag": s["tag"],
                "tag_color": s["tag_color"],
                "center": s["center"],
                "zoom": s["zoom"],
                "description": s["description"],
                "incident_date": s["incident_date"],
                "peak_magnitude": s["peak_magnitude"],
                "event_count": len(s["events"]),
            }
            for s in SCENARIOS
        ],
    }), 200


@scenarios_bp.get("/scenarios/<scenario_id>")
def get_scenario_details(scenario_id: str):
    """Retrieve full details and sequence events for a specific scenario."""
    matched = next((s for s in SCENARIOS if s["id"] == scenario_id), None)
    if not matched:
        return jsonify({"error": f"Scenario '{scenario_id}' not found"}), 404
    return jsonify(matched), 200
